import type { TripDataConfidence } from "@/types/trip"

export type TravelMonthClimate = {
  avgTemp: number
  rainProbability: number
  comfortScore: number
  snowProbability?: number
}

export type TravelDestinationData = {
  destination: string
  country: string
  region: string
  tags: string[]
  bestMonths?: number[]
  highSeasonMonths: number[]
  lowSeasonMonths: number[]
  avgDailyCostBRL: number
  familyScore: number
  romanticScore: number
  adventureScore: number
  cultureScore: number
  natureScore: number
  nightlifeScore: number
  foodScore: number
  walkabilityScore: number
  safetyScore: number
  mobilityScore: number
  climateByMonth: Record<number, TravelMonthClimate>
  crowdIndexByMonth: Record<number, number>
  recommendedTripDays: [number, number]
  estimatedFlightCostBRL: {
    domesticOrigin: number
    internationalOrigin: number
  }
  estimatedFlightDurationHours?: {
    domesticOrigin?: number
    internationalOrigin?: number
  }
  localTransportDailyBRL: number
  foodDailyBRL: {
    economico: number
    intermediario: number
    premium: number
  }
  lodgingDailyBRL: {
    economico: number
    intermediario: number
    premium: number
  }
}

export type TravelRegionFallback = Omit<TravelDestinationData, "destination" | "country"> & {
  country: string
  profileSummary: string
  dataConfidence: TripDataConfidence
}

function buildClimate(
  months: Array<[number, number, number, number, number?]>,
): Record<number, TravelMonthClimate> {
  return Object.fromEntries(
    months.map(([month, avgTemp, rainProbability, comfortScore, snowProbability]) => [
      month,
      { avgTemp, rainProbability, comfortScore, ...(typeof snowProbability === "number" ? { snowProbability } : {}) },
    ]),
  )
}

function buildCrowd(values: Array<[number, number]>): Record<number, number> {
  return Object.fromEntries(values)
}

